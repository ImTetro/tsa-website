// Writes public/_redirects (Netlify format) from OLD_URLS in src/site.ts — the single source of truth.
// Each old Wix path gets two lines: the raw (Hebrew) path and its percent-encoded form, both 301.
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const out = 'node_modules/.cache/gen-redirects/site.mjs';
mkdirSync('node_modules/.cache/gen-redirects', { recursive: true });
await build({ entryPoints: ['src/site.ts'], bundle: true, format: 'esm', platform: 'node', outfile: out, logLevel: 'silent' });
const { OLD_URLS } = await import(pathToFileURL(out).href + '?t=' + Date.now());

const lines = ['# generated by scripts/gen-redirects.mjs from OLD_URLS in src/site.ts – do not edit by hand'];
for (const [from, to] of OLD_URLS) {
  lines.push(`${from} ${to} 301`);
  const enc = encodeURI(from);
  if (enc !== from) lines.push(`${enc} ${to} 301`);
}
writeFileSync('public/_redirects', lines.join('\n') + '\n', 'utf8');
console.log(`_redirects: ${lines.length - 1} rules`);
